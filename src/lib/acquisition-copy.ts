/** "12 ΒΘΠ members are cramming" / "1 ΒΘΠ member is cramming" — or null. No social proof until there is some. */
export function membersCrammingLine(letters: string | null | undefined, members: number | null | undefined): string | null {
  const n = typeof members === "number" && Number.isFinite(members) ? Math.floor(members) : 0;
  if (n <= 0) return null;
  const who = (letters ?? "").trim();
  return `${n} ${who ? `${who} ` : ""}member${n === 1 ? " is" : "s are"} cramming`;
}

