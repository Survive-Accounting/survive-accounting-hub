/** Council exec → scholarship chairs. Survive Accounting provides the pages; the council only forwards the link. */
export function councilShareMessage(o: { courseCode: string | null | undefined; councilLink: string }): string {
  const c = courseFor(o.courseCode);
  return [
    `Scholarship chairs — Survive Accounting set up ${c} study pages for every chapter, with short cram videos + practice exams. Students can start free.`,
    "",
    "Pick your chapter here to get your member link, GroupMe post, and flyer:",
    o.councilLink,
  ].join("\n");
}

